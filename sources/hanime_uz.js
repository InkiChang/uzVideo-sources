async function getPlayinfo(ext) {
    ext = argsify(ext)
    const url = ext.url

    const { data } = await $fetch.get(url, {
        headers: {
            'User-Agent': UA,
        },
    })

    const $ = cheerio.load(data)
    const json = $('script[type=application/ld+json]').text()

    let playUrl = json.match(/contentUrl":\s?"(.*?)",/)[1]

    return jsonify({ urls: [playUrl] })
}

